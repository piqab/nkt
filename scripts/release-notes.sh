#!/bin/sh
# Печатает описание релиза для тега из WHATSNEW.md.
#
# Разделы в файле идут от новых к старым и озаглавлены "## vX.Y.Z". Версия
# бампается почти каждым коммитом, а тег ставится реже — значит между двумя
# тегами накапливается несколько разделов, и в описание релиза должны попасть
# все они, а не только раздел самого тега.
#
#   scripts/release-notes.sh v1.8.80 [v1.8.78]
#
# Первый аргумент — выпускаемый тег, второй (необязательный) — предыдущий:
# печать начинается с раздела первого и обрывается на разделе второго, не
# включая его. Без второго аргумента печатается всё до конца файла — это
# верно для первого релиза с этим файлом, где старых разделов просто нет.
#
# Если раздела для тега в файле нет, вывод пустой и код возврата 1 — вызов в
# .github/workflows/release.yml понимает это как "откатиться на
# --generate-notes", чтобы релиз не вышел с пустым описанием.
set -eu

tag="${1:?использование: release-notes.sh <тег> [предыдущий-тег]}"
prev="${2:-}"
file="${WHATSNEW_FILE:-$(dirname "$0")/../WHATSNEW.md}"

notes="$(awk -v tag="$tag" -v prev="$prev" '
  # Заголовок раздела: "## v1.8.80" или "## v1.8.80 — 2026-09-08".
  /^## v/ {
    version = $2
    if (version == tag) { printing = 1; print; next }
    # Раздел предыдущего тега и всё под ним уже вышло прошлым релизом.
    if (printing && prev != "" && version == prev) exit
  }
  printing { print }
' "$file")"

# Хвостовые пустые строки от последнего раздела.
notes="$(printf '%s\n' "$notes" | sed -e :a -e '/^[[:space:]]*$/{$d;N;ba' -e '}')"

if [ -z "$(printf '%s' "$notes" | tr -d '[:space:]')" ]; then
  echo "release-notes.sh: в $file нет раздела для $tag" >&2
  exit 1
fi

printf '%s\n' "$notes"
